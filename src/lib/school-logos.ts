export type SchoolLogo = {
  /** Must match the school name the app renders. */
  school: string;
  /** Path under public/. Always a normalised 512x512 PNG. */
  file: string;
  /**
   * Whether the asset came from the institution itself or from a third party.
   *
   * "official" means it was found on a domain belonging to the university.
   * "secondary" means a reputable third party (Wikidata/Wikimedia Commons),
   * which is weaker on both identity and rights and is reported separately.
   */
  origin: "official" | "secondary";
  /** The page the asset was found on. */
  declaredOn: string;
  /** The absolute URL the bytes came from. */
  sourceUrl: string;
  /** Which strategy found it, for the record: "declared icon", "header logo", ... */
  via: string;
  /** The university domain this was attributed to. */
  domain: string;
  /**
   * True when the source was a designed app icon whose colour field runs to
   * the edge. Those keep their field; everything else is trimmed to its real
   * content and re-inset, so perceived size stays consistent.
   */
  fullBleed: boolean;
  /** Aspect ratio of the real content, after trimming. */
  aspect: number;
  /** Long edge of the real content in source pixels, before normalising. */
  contentPx: number;
  /** e.g. "png", "svg", "png embedded in ico". */
  sourceFormat: string;
  /** Source dimensions before normalising, e.g. "229x256". */
  sourceSize: string;
  /** sha256 of the normalised bytes. */
  sha256: string;
  /** ISO date the asset was retrieved. */
  retrievedAt: string;
  /**
   * Per-school rendering escape hatch, for the rare mark that the automatic
   * treatment gets wrong. `scale` multiplies the content size; `background`
   * overrides the disc colour.
   */
  render?: { scale?: number; background?: string };
  /** Anything a human should know, including doubts. */
  note?: string;
};

