/**
 * Whether logos are shown at all.
 *
 * This used to require `SHOW_SCHOOL_LOGOS=1`, back when the files were
 * gitignored and the registry was empty in the committed source: three
 * independent gates so that trademarked marks could not ship by accident.
 *
 * The owner has now deliberately opened the other two - the assets are
 * committed and the registry is populated - so keeping the environment gate
 * would only mean a deploy that silently renders initials. Committing the
 * files *is* the deliberate act now. An empty registry still renders initials,
 * and `SHOW_SCHOOL_LOGOS=0` still forces them off, which is the switch to reach
 * for if a takedown request ever arrives.
 */
export function logosEnabled(): boolean {
  if (process.env.SHOW_SCHOOL_LOGOS === "0") return false;
  return SCHOOL_LOGOS.length > 0;
}

const flatten = (name: string) => name.toLowerCase().replace(/[^a-z0-9]+/g, " ").trim();

/**
 * Shorter forms of a school's name that still identify it unambiguously.
 *
 * A workspace stores whatever name the student typed or the catalogue imported,
 * and those disagree: this database holds both "University of Maryland" and
 * "University of Maryland, College Park". An exact-match lookup gave the
 * shorter one initials while the longer one had a logo.
 *
 * A campus suffix is only dropped when the remainder belongs to exactly one
 * school. "University of Maryland, College Park" yields "University of
 * Maryland" because nothing else claims it; "University of California,
 * Berkeley" yields nothing, because seven campuses would answer to "University
 * of California" and a wrong mark is worse than initials.
 */
function buildIndex(): Map<string, SchoolLogo> {
  const index = new Map<string, SchoolLogo>();
  for (const logo of SCHOOL_LOGOS) index.set(flatten(logo.school), logo);

  const contenders = new Map<string, SchoolLogo[]>();
  for (const logo of SCHOOL_LOGOS) {
    const shortened = [
      logo.school.split(",")[0],
      logo.school.split(" at ")[0],
      logo.school.split(/\s*[-–—]\s*/)[0],
    ];
    for (const candidate of shortened) {
      const key = flatten(candidate);
      if (!key || index.has(key)) continue;
      contenders.set(key, [...(contenders.get(key) ?? []), logo]);
    }
  }
  for (const [key, matches] of contenders) {
    if (matches.length === 1) index.set(key, matches[0]);
  }
  return index;
}

let index: Map<string, SchoolLogo> | null = null;

export function logoForSchool(name: string): SchoolLogo | undefined {
  if (!logosEnabled()) return undefined;
  if (DECLINED_SCHOOLS.includes(name) || NO_USABLE_LOGO.includes(name)) return undefined;
  index ??= buildIndex();
  const found = index.get(flatten(name));
  if (!found) return undefined;
  // The alias must not resurrect a school that was deliberately excluded.
  if (DECLINED_SCHOOLS.includes(found.school) || NO_USABLE_LOGO.includes(found.school)) return undefined;
  return found;
}
